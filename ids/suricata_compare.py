"""Suricata baseline (core tier, part A): fit rules fairly, then compare on identical input.

Suricata cannot see inside TLS. Against our fleet it is limited to:
  - flow/volume signals (packet counts and rates per source), and
  - what the TLS handshake exposes in cleartext: in TLS 1.3 that is the ClientHello
    (SNI, JA3/JA4 fingerprints) but NOT the certificates, which are encrypted.
So the rule set is: a JA4 + JA3 fingerprint allow-list (handshake rules) and an upstream
packet-rate rule (flow rule). An IP/identity rule ("traffic to the broker from a non-device
address") would catch our attacker trivially, but ground truth is itself defined by IP, so it
is excluded from the like-for-like comparison, as the ML evaluation excludes it.

Fairness: the rate threshold is fitted on train-A only (as the threshold rule is), and the
fingerprint allow-list comes from benign fleet handshakes captured in M2 — never from test-B.

    python -m ids.suricata_compare fit-rules --train train-A --fleet-eve EVE --out RULES
    python -m ids.suricata_compare compare --train train-A --test test-B --eve EVE --model PATH
"""

from __future__ import annotations

import argparse
import json
import math
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

import joblib
import numpy as np

from ids.baselines import ThresholdRule
from ids.evaluate import false_alarms_per_hour, metrics
from ids.labeling import to_xy
from ids.train import load_runs

BROKER = "172.28.0.10"
FLEET_PREFIX = "172.28.0.1"  # devices are 172.28.0.101-110
WINDOW_S = 5.0
SID_JA4, SID_JA3, SID_RATE = 9000001, 9000002, 9000010


def fleet_fingerprints(eve_path: Path) -> tuple[set[str], set[str]]:
    """JA4 and JA3 hashes of benign fleet devices' ClientHellos (from a benign capture)."""
    ja4, ja3 = set(), set()
    for line in eve_path.open():
        e = json.loads(line)
        if e.get("event_type") != "tls" or not e["src_ip"].startswith(FLEET_PREFIX) or len(e["src_ip"]) != 12:
            continue
        t = e["tls"]
        if t.get("ja4"):
            ja4.add(t["ja4"])
        if (t.get("ja3") or {}).get("hash"):
            ja3.add(t["ja3"]["hash"])
    return ja4, ja3


def fit_rules(args) -> None:
    root = Path(args.runs_root)
    Xtr, ytr, _ = to_xy(load_runs(args.train, root, WINDOW_S))
    rate = ThresholdRule("data_pkts_up").fit(Xtr, ytr)
    count = int(math.floor(rate.threshold_)) + 1  # alert when >= count data packets in 5 s
    ja4, ja3 = fleet_fingerprints(Path(args.fleet_eve))
    if len(ja4) != 1 or len(ja3) != 1:
        raise SystemExit(f"expected one fleet fingerprint, got JA4={ja4} JA3={ja3}")
    (j4,), (j3,) = ja4, ja3
    rules = f"""# GENERATED by `python -m ids.suricata_compare fit-rules` -- do not edit by hand.
# Fitted on: train run(s) {', '.join(args.train)} (rate count) and benign fleet handshakes from
# the M2 capture (fingerprint allow-list). Never fitted on test data.
#
# Handshake rules: in TLS 1.3 the ClientHello is the only cleartext part of the handshake;
# certificates are encrypted, so certificate-field rules cannot apply to this fleet.
alert tls any any -> {BROKER} 8883 (msg:"IRON TLS client JA4 not in fleet allow-list"; flow:to_server; ja4.hash; content:!"{j4}"; classtype:policy-violation; sid:{SID_JA4}; rev:1;)
alert tls any any -> {BROKER} 8883 (msg:"IRON TLS client JA3 not in fleet allow-list"; flow:to_server; ja3.hash; content:!"{j3}"; classtype:policy-violation; sid:{SID_JA3}; rev:1;)
#
# Flow rule: upstream data packets per source. Count {count} = train-A threshold
# (data_pkts_up > {rate.threshold_:.1f} per 5 s window maximised F1 on train-A).
alert tcp any any -> {BROKER} 8883 (msg:"IRON upstream packet rate above train-A threshold"; flow:to_server,established; dsize:>0; threshold:type threshold, track by_src, count {count}, seconds 5; classtype:attempted-dos; sid:{SID_RATE}; rev:1;)
"""
    Path(args.out).write_text(rules)
    print(f"wrote {args.out}: rate count {count} per 5 s (train-A), JA4 allow {j4}, JA3 allow {j3}")


def _epoch(ts: str) -> float:
    return datetime.strptime(ts, "%Y-%m-%dT%H:%M:%S.%f%z").timestamp()


def alert_windows(eve_path: Path, sids: set[int]) -> tuple[set[tuple[str, float]], Counter]:
    flagged, counts = set(), Counter()
    for line in eve_path.open():
        e = json.loads(line)
        if e.get("event_type") != "alert" or e["alert"]["signature_id"] not in sids:
            continue
        counts[(e["alert"]["signature_id"], e["src_ip"])] += 1
        flagged.add((e["src_ip"], math.floor(_epoch(e["timestamp"]) / WINDOW_S) * WINDOW_S))
    return flagged, counts


def compare(args) -> None:
    root = Path(args.runs_root)
    Xtr, ytr, _ = to_xy(load_runs(args.train, root, WINDOW_S))
    Xte, yte, meta = to_xy(load_runs(args.test, root, WINDOW_S))
    bundle = joblib.load(args.model)
    ml_pred = bundle["model"].predict(Xte)
    th = ThresholdRule().fit(Xtr, ytr)
    th_pred = th.predict(Xte)
    keys = [(m["client_ip"], m["window_start"]) for m in meta]

    eve = Path(args.eve)
    detectors = [("ML (gradient boosting)", ml_pred), (f"threshold payload_up>{th.threshold_:.0f}", th_pred)]
    alert_counts = Counter()
    for name, sids in [("Suricata rate rule", {SID_RATE}),
                       ("Suricata JA4/JA3 rules", {SID_JA4, SID_JA3}),
                       ("Suricata all rules", {SID_RATE, SID_JA4, SID_JA3})]:
        flagged, counts = alert_windows(eve, sids)
        alert_counts.update(counts if name == "Suricata all rules" else {})
        detectors.append((name, np.array([1 if k in flagged else 0 for k in keys])))

    print(f"test run(s) {args.test}: {len(yte)} windows, {int(yte.sum())} attack / {int((yte == 0).sum())} benign")
    print(f"\n{'detector':34} {'prec':>6} {'recall':>6} {'f1':>6} {'tp':>4} {'fp':>4} {'fn':>4} {'tn':>5} {'FP/hr':>6}")
    table = {}
    for name, pred in detectors:
        m = metrics(yte, pred)
        m["fp_per_hour"] = false_alarms_per_hour(pred, yte, WINDOW_S)
        table[name] = m
        print(f"{name:34} {m['precision']:6} {m['recall']:6} {m['f1']:6} {m['tp']:4} {m['fp']:4} "
              f"{m['fn']:4} {m['tn']:5} {m['fp_per_hour']:6}")
    print("\nSuricata alerts by (sid, src_ip):")
    for (sid, ip), n in sorted(alert_counts.items()):
        print(f"  sid {sid} from {ip}: {n}")
    if args.json:
        Path(args.json).write_text(json.dumps({"table": table, "alerts": {f"{s}:{ip}": n for (s, ip), n in alert_counts.items()}}, indent=2))
    print("\nSURICATA COMPARE: done")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fit-rules")
    f.add_argument("--train", nargs="+", required=True)
    f.add_argument("--fleet-eve", required=True)
    f.add_argument("--out", required=True)
    c = sub.add_parser("compare")
    c.add_argument("--train", nargs="+", required=True)
    c.add_argument("--test", nargs="+", required=True)
    c.add_argument("--eve", required=True)
    c.add_argument("--model", required=True)
    c.add_argument("--json", default=None)
    for p in (f, c):
        p.add_argument("--runs-root", default="/captures/runs")
    args = ap.parse_args()
    fit_rules(args) if args.cmd == "fit-rules" else compare(args)


if __name__ == "__main__":
    main()
