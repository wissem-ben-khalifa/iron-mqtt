#!/usr/bin/env python3
"""Generate compose.devices.yaml: one Compose service per simulated device.

Each device gets its own container, its own static IP on iot_net and ONLY its own
certificate mounted, so identity, Ping and Wireshark are all per-device.
Stdlib only (runs on the host without a virtualenv).

    python3 scripts/gen_devices.py            # 10 devices
    python3 scripts/gen_devices.py --count 30 # scale (run ./iron certs with DEVICES=30 first)
"""

from __future__ import annotations

import argparse
from pathlib import Path

# Type mix per block of 10 devices: 3 env sensors, 3 plugs, 2 doors, 2 cameras.
CYCLE = ["env_sensor", "smart_plug", "door_sensor", "camera", "env_sensor",
         "smart_plug", "env_sensor", "smart_plug", "door_sensor", "camera"]
IP_BASE = 100  # device-NN -> 172.28.0.(100+NN)


def device_service(n: int, seed: int) -> str:
    dev = f"device-{n:02d}"
    return f"""  {dev}:
    <<: *device
    hostname: {dev}
    environment:
      DEVICE_ID: {dev}
      DEVICE_TYPE: {CYCLE[(n - 1) % len(CYCLE)]}
      SEED: "{seed}"
    volumes:
      - ./certs/ca/ca.crt:/certs/ca.crt:ro
      - ./certs/devices/{dev}.crt:/certs/client.crt:ro
      - ./certs/devices/{dev}.key:/certs/client.key:ro
    networks:
      iot_net:
        ipv4_address: 172.28.0.{IP_BASE + n}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--count", type=int, default=10)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default="compose.devices.yaml")
    args = ap.parse_args()
    if not 1 <= args.count <= 99:
        raise SystemExit("--count must be 1..99")

    header = f"""# GENERATED by scripts/gen_devices.py --count {args.count} --seed {args.seed}. Do not edit by hand.
# Merged with compose.yaml via COMPOSE_FILE (set by ./iron).

x-device: &device
  image: iron-mqtt/app:dev
  pull_policy: never
  command: ["python", "-m", "services.device"]
  restart: unless-stopped
  mem_limit: 128m
  depends_on:
    broker:
      condition: service_healthy

services:
"""
    body = "".join(device_service(n, args.seed) for n in range(1, args.count + 1))
    Path(args.out).write_text(header + body)
    print(f"wrote {args.out}: {args.count} devices")


if __name__ == "__main__":
    main()
